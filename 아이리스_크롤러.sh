#!/usr/bin/env bash
set -euo pipefail

# ─────────────────────────────────────────────
# 0. 기본 변수 (필요하면 경로/파일명 수정)
# ─────────────────────────────────────────────
VENV_DIR=".venv"          # 가상환경 위치
SCRIPT="main.py"       # 파이썬 크롤러 파일

# ─────────────────────────────────────────────
# 1. Python 3 - venv 생성
# ─────────────────────────────────────────────
python3 -m venv "$VENV_DIR"
source "$VENV_DIR/bin/activate"

# ─────────────────────────────────────────────
# 2. 패키지 설치
# ─────────────────────────────────────────────
python -m pip install --upgrade pip
pip install requests beautifulsoup4 lxml pymongo

# ─────────────────────────────────────────────
# 3. 크롤러 실행
# ─────────────────────────────────────────────
python "$SCRIPT"
